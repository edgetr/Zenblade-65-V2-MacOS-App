const COMMANDS: &[&str] = &[
    "app_get_info",
    "app_get_active_application",
    "app_set_desktop_state",
    "app_get_system_context",
    "app_configure_system_shortcuts",
    "app_choose_applications",
    "app_export_profile",
    "app_import_profile",
    "hid_get_devices",
    "hid_open",
    "hid_close",
    "hid_send",
];

/// Test-harness commands, only in `--features e2e` builds.
const E2E_COMMANDS: &[&str] = &["e2e_log", "e2e_window", "e2e_snapshot"];

fn main() {
    // An app manifest turns on command ACLs: only capabilities that list a
    // command (the main window's) can invoke it.
    let mut commands = COMMANDS.to_vec();
    if std::env::var_os("CARGO_FEATURE_E2E").is_some() {
        commands.extend_from_slice(E2E_COMMANDS);
    } else {
        // tauri-build never deletes generated permission files; drop the test
        // ones so release builds carry no trace of the harness.
        for command in E2E_COMMANDS {
            let _ = std::fs::remove_file(format!("permissions/autogenerated/{command}.toml"));
        }
    }
    let commands: &'static [&'static str] = Box::leak(commands.into_boxed_slice());
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(commands)),
    )
    .expect("failed to run tauri-build");
}
